def get_role_card(role: str) -> str:
    """Get the ASCII role card for a given role."""
    cards = {
        "Mafia": ROLE_CARD_MAFIA,
        "Villager": ROLE_CARD_VILLAGER,
        "Detective": ROLE_CARD_DETECTIVE,
        "Doctor": ROLE_CARD_DOCTOR,
    }
    return cards.get(role, ROLE_CARD_VILLAGER)


def get_tombstone(name: str) -> str:
    """Get a tombstone with the player's name."""
    # Center the name in the tombstone
    padded = name.center(9)
    return TOMBSTONE.replace("{name}", padded)
